"""
Prepares the Oxford-102 Flowers dataset for training.
Run once after generate_captions.py:
  python src/data/prepare_dataset.py

What it does:
  1. Reads train/val/test split IDs from setid.mat
  2. Reads species label per image from imagelabels.mat
  3. Resizes + center-crops every image to 512x512
  4. Reads BLIP caption from data/raw/captions/
  5. Writes data/processed/metadata.jsonl  (one JSON object per image)
  6. Writes data/splits/train.txt, val.txt, test.txt
"""
import argparse
import json
import os
from PIL import Image                # image resizing
import scipy.io                      # read .mat files
from tqdm import tqdm                # progress bar


RAW_IMAGES_DIR  = "data/raw/jpg"
RAW_CAPTIONS_DIR = "data/raw/captions"
SETID_PATH      = "data/raw/setid.mat"
LABELS_PATH     = "data/raw/imagelabels.mat"
OUT_IMAGES_DIR  = "data/processed/images"   # split subdirs created below
OUT_METADATA    = "data/processed/metadata.jsonl"
SPLITS_DIR      = "data/splits"


def load_splits():
    """Returns dict with train/val/test image IDs (1-indexed) from Oxford."""
    mat = scipy.io.loadmat(SETID_PATH)
    return {
        "train": mat["trnid"].flatten().tolist(),   # training image IDs
        "val":   mat["valid"].flatten().tolist(),   # validation image IDs
        "test":  mat["tstid"].flatten().tolist(),   # test image IDs
    }


def load_labels():
    """Returns list of species labels (1-102), one per image."""
    mat = scipy.io.loadmat(LABELS_PATH)
    return mat["labels"].flatten().tolist()          # index = image_id - 1


def process_image(src_path, dst_path, resolution=512):
    """Resize short side to resolution, then center-crop to square."""
    img = Image.open(src_path).convert("RGB")
    w, h = img.size
    scale = resolution / min(w, h)                   # scale short side to 512
    new_w, new_h = int(w * scale), int(h * scale)
    img = img.resize((new_w, new_h), Image.BILINEAR)
    left = (img.width  - resolution) // 2            # center crop x offset
    top  = (img.height - resolution) // 2            # center crop y offset
    img = img.crop((left, top, left + resolution, top + resolution))
    img.save(dst_path)


def main(resolution=512):
    # create split subdirectories — FID needs real test images in their own folder
    for split_name in ["train", "val", "test"]:
        os.makedirs(os.path.join(OUT_IMAGES_DIR, split_name), exist_ok=True)
    os.makedirs(SPLITS_DIR, exist_ok=True)

    splits = load_splits()                            # {train: [ids], val: [ids], test: [ids]}
    labels = load_labels()                            # [label_1, label_2, ..., label_8189]

    # build a lookup: image_id -> split name
    id_to_split = {}
    for split_name, ids in splits.items():
        for img_id in ids:
            id_to_split[img_id] = split_name

    metadata = []
    split_files = {"train": [], "val": [], "test": []}

    image_files = sorted(os.listdir(RAW_IMAGES_DIR))

    for filename in tqdm(image_files, desc="Processing"):
        if not filename.endswith(".jpg"):
            continue

        # Oxford images are named image_00001.jpg → id = 1
        img_id = int(filename.replace("image_", "").replace(".jpg", ""))

        # read caption (generated by BLIP)
        caption_path = os.path.join(RAW_CAPTIONS_DIR, filename.replace(".jpg", ".txt"))
        if not os.path.exists(caption_path):
            print(f"Skipping {filename} — no caption found")
            continue

        with open(caption_path) as f:
            caption = f.read().strip().lower()       # clean caption text

        split = id_to_split.get(img_id, "train")     # default to train if not found

        # resize + crop image — save into split subfolder
        dst_path = os.path.join(OUT_IMAGES_DIR, split, filename)
        process_image(os.path.join(RAW_IMAGES_DIR, filename), dst_path, resolution)
        label = labels[img_id - 1]                   # 1-indexed → 0-indexed

        item = {
            "image_path": dst_path,                  # path to processed image
            "caption":    caption,                   # BLIP-generated caption
            "label":      label,                     # species ID (1-102)
            "split":      split,                     # train / val / test
        }
        metadata.append(item)
        split_files[split].append(dst_path)

    # write metadata.jsonl
    with open(OUT_METADATA, "w") as f:
        for item in metadata:
            f.write(json.dumps(item) + "\n")         # one JSON object per line

    # write split files
    for split_name, paths in split_files.items():
        with open(os.path.join(SPLITS_DIR, f"{split_name}.txt"), "w") as f:
            f.write("\n".join(paths))

    print(f"\nDone. {len(metadata)} images processed.")
    for split_name, paths in split_files.items():
        print(f"  {split_name}: {len(paths)} images")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--resolution", type=int, default=512)
    args = parser.parse_args()
    main(args.resolution)
